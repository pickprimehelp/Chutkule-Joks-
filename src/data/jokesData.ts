// Generates up to totalCount items for a given category deterministically
export function getItemsForCategory(categoryId: CategoryId, totalCount: number = 1050): Item[] {
  const base = BASE_ITEMS[categoryId] || [];
  const items: Item[] = base.map((item) => ({
    ...item,
    categoryId,
  }));

  const template = TEMPLATES[categoryId];
  if (!template) return items;

  const currentCount = items.length;
  const needed = Math.max(0, totalCount - currentCount);

  for (let i = 0; i < needed; i++) {
    const sIdx = (i * 3 + 1) % template.setups.length;
    const tIdx = (i * 5 + 2) % template.twists.length;
    const cIdx = (i * 7 + 3) % template.characters.length;

    const setup = template.setups[sIdx];
    const twist = template.twists[tIdx];
    const character = template.characters[cIdx];

    // Add slight variety based on index
    const variantNumber = i + 1;
    let fullText = `${setup}\n${twist}`;
    if (variantNumber % 4 === 0) {
      fullText = `"${setup} ${twist}"`;
    }

    const likes = 600 + ((i * 137) % 4500);
    const tags = [
      template.tags[i % template.tags.length],
      template.tags[(i + 2) % template.tags.length],
    ];

    items.push({
      id: `${categoryId}-${variantNumber + 20}`,
      categoryId,
      text: fullText,
      authorOrCharacter: `${character} #${variantNumber}`,
      likes,
      tags,
      isFeatured: i === 12 || i === 45,
    });
  }

  return items;
}

// Quick helper to fetch a specific quote of the day
export function getDailyQuote(category?: CategoryId): Item {
  const today = new Date();
  const dayOfYear = Math.floor(
    (today.getTime() - new Date(today.getFullYear(), 0, 0).getTime()) / 1000 / 60 / 60 / 24
  );

  const cat = category || 'motivational_quotes';
  const pool = getItemsForCategory(cat, 100);
  const selected = pool[dayOfYear % pool.length] || pool[0];
  return selected;
}
